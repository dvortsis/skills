"""Regenerate a skill's CHECKS.md index (same format as the original generator). Usage: gen_checks.py SKILL_DIR NAME [OUT]"""
import os, re, sys

skill, name = sys.argv[1], sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else None
rows = []
tests = {}
sd = os.path.join(skill, "scripts")
for f in sorted(os.listdir(sd)):
    if f.startswith("test_") and f.endswith(".py"):
        tests[f] = open(os.path.join(sd, f), encoding="utf-8").read()


def scan(fname, pats):
    lines = open(os.path.join(sd, fname), encoding="utf-8").read().split("\n")
    func = ""
    for i, ln in enumerate(lines, 1):
        m = re.match(r"\s*def (\w+)\(", ln)
        if m:
            func = m.group(1)
        for pat in pats:
            for code, sev in pat(ln):
                rows.append((code, sev, "scripts/" + fname, func, i))


def markers(ln):
    return [(c, s) for c, s in re.findall(r"# check: ([A-Z0-9_]+) (FAIL|WARN|INFO)", ln)]


def adds(ln):
    return [(c, s) for s, c in re.findall(r'add\("(FAIL|WARN)", "([A-Z0-9_]+)"', ln)]


for f in sorted(os.listdir(sd)):  # every gate script: `# check: CODE LEVEL` markers and add("LEVEL", "CODE") calls
    if f.endswith(".py") and not f.startswith("test_") and f != "preflight.py":
        scan(f, [markers, adds])
rows.sort(key=lambda r: (r[0], r[1], r[2], r[3], r[4]))
o = ["# CHECKS: %s" % name, "", "Generated by tools/gen_checks.py; do not edit. Find a check here, then open only the line it points to.", "",
     "| Code | Severity | File | Function | Line | Tests |", "|---|---|---|---|---|---|"]
for code, sev, f, fn, ln in rows:
    t = ", ".join("scripts/" + k for k, v in tests.items() if re.search(r"\b%s\b" % code, v)) or "none"
    o.append("| %s | %s | %s | %s | %d | %s |" % (code, sev, f, fn, ln, t))
o += ["", "## Checks by file", ""]
byf = {}
for code, sev, f, fn, ln in rows:
    byf.setdefault(f, set()).add(code)
for f in sorted(byf):
    o.append("* `%s`: %s" % (f, ", ".join(sorted(byf[f]))))
text = "\n".join(o) + "\n"
if out:
    open(out, "w", encoding="utf-8", newline="\n").write(text)
else:
    sys.stdout.write(text)
